#!/usr/bin/env python3
"""
Auto Form Fill AI Agent
A true AI agent that intelligently analyzes forms and fills them automatically.
"""

import json
import argparse
import logging
from datetime import datetime
from pathlib import Path
from playwright.sync_api import sync_playwright 
from resume_parser import parse_resume_to_json
from form_agent import analyze_form_with_ai, extract_form_fields

# Setup logging
LOG_DIR = Path("logs")
LOG_DIR.mkdir(exist_ok=True)
log_file = LOG_DIR / f"ai_agent_{datetime.now().strftime('%Y%m%d_%H%M%S')}.log"

logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.FileHandler(log_file, encoding='utf-8'),
        logging.StreamHandler()
    ]
)
logger = logging.getLogger(__name__)

# Default settings
DEFAULT_URL = "https://demo.automationtesting.in/Register.html"
HEADLESS = True
SLOW_MOTION = 0
WAIT_TIME = 2000


def load_profile(profile_path="profile.json"):
    """Load and validate user profile from JSON file."""
    try:
        with open(profile_path, "r", encoding="utf-8") as f:
            profile = json.load(f)
            
        required_fields = ['personal_info', 'address', 'skills']
        for field in required_fields:
            if field not in profile:
                raise ValueError(f"Missing required field: {field}")
        
        logger.info(f"Successfully loaded profile from {profile_path}")
        return profile
    except FileNotFoundError:
        logger.warning(f"{profile_path} not found")
        return None
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in {profile_path}: {e}")
        raise
    except Exception as e:
        logger.error(f"Error loading profile: {e}")
        raise


def fill_form_with_ai(page, user_profile):
    """
    AI Agent: Uses AI to analyze form and intelligently fill it.
    """
    logger.info("AI Agent: Analyzing form structure...")
    
    # Step 1: Extract form fields from page
    form_fields = extract_form_fields(page)
    logger.info(f"AI Agent: Detected {len(form_fields)} form fields")
    
    if not form_fields:
        logger.error("AI Agent: No form fields found on page")
        return 0, 0, []
    
    # Step 2: Use AI to analyze and create field mapping
    logger.info("AI Agent: Consulting AI for intelligent field mapping...")
    field_mapping = analyze_form_with_ai(form_fields, user_profile)
    
    if not field_mapping:
        logger.error("AI Agent: No field mappings generated by AI")
        return 0, 0, []
    
    logger.info(f"AI Agent: Generated {len(field_mapping)} field mappings")
    logger.info(f"AI Decisions: {json.dumps(field_mapping, indent=2)}")
    
    # Step 3: Execute AI's filling plan
    filled_count = 0
    total_fields = len(field_mapping)
    failed_fields = []
    
    logger.info("AI Agent: Executing filling plan...")
    
    for selector, value in field_mapping.items():
        try:
            element = page.locator(selector).first
            
            if element.count() == 0:
                logger.warning(f"AI Agent: Selector '{selector}' not found on page")
                failed_fields.append(selector)
                continue
            
            # Handle different field types
            tag_name = element.evaluate("el => el.tagName.toLowerCase()")
            
            if tag_name == "select":
                # Dropdown field
                try:
                    element.select_option(label=value)
                    logger.info(f"[OK] AI filled dropdown '{selector}' = '{value}'")
                except:
                    try:
                        element.select_option(value=value)
                        logger.info(f"[OK] AI filled dropdown '{selector}' = '{value}'")
                    except:
                        element.select_option(index=1)
                        logger.info(f"[OK] AI filled dropdown '{selector}' (first option)")
            else:
                # Text input or textarea
                element.fill(str(value))
                logger.info(f"[OK] AI filled '{selector}' = '{value}'")
            
            filled_count += 1
            page.wait_for_timeout(200)  # Small delay between fields
            
        except Exception as e:
            logger.warning(f"[X] AI Agent failed to fill '{selector}': {e}")
            failed_fields.append(selector)
    
    return filled_count, total_fields, failed_fields


def main(resume_path="resume.pdf", profile_path="profile.json", url=None, headless=None, screenshot=False):
    """Main function to run the AI agent."""
    start_time = datetime.now()
    logger.info("=" * 60)
    logger.info("AI Form Filling Agent - Starting Session")
    logger.info("=" * 60)
    
    target_url = url or DEFAULT_URL
    run_headless = headless if headless is not None else HEADLESS
    
    logger.info(f"Target URL: {target_url}")
    logger.info(f"Mode: {'Headless' if run_headless else 'Visible'} AI Agent")
    logger.info(f"Log file: {log_file}")
    
    # Load or generate profile
    user_profile = load_profile(profile_path)
    if not user_profile:
        logger.info(f"Parsing resume from {resume_path}...")
        try:
            user_profile = parse_resume_to_json(resume_path, profile_path)
            logger.info(f"Resume parsed successfully and saved to {profile_path}")
        except Exception as e:
            logger.error(f"Failed to parse resume: {e}")
            return 1
    
    # Start browser automation
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=run_headless, slow_mo=SLOW_MOTION)
        page = browser.new_page()
        
        try:
            logger.info(f"Navigating to: {target_url}")
            page.goto(target_url)
            page.wait_for_load_state("networkidle")
            logger.info("Page loaded successfully")
            
            # AI Agent fills the form
            filled_count, total_fields, failed_fields = fill_form_with_ai(page, user_profile)
            
            # Take screenshot if requested
            if screenshot:
                screenshot_dir = Path("screenshots")
                screenshot_dir.mkdir(exist_ok=True)
                screenshot_path = screenshot_dir / f"ai_agent_{datetime.now().strftime('%Y%m%d_%H%M%S')}.png"
                page.screenshot(path=str(screenshot_path))
                logger.info(f"Screenshot saved: {screenshot_path}")
            
            # Wait before closing
            page.wait_for_timeout(WAIT_TIME)
            
            # Summary
            duration = (datetime.now() - start_time).total_seconds()
            success_rate = (filled_count / total_fields * 100) if total_fields > 0 else 0
            
            logger.info("=" * 60)
            logger.info("AI Agent Session Summary")
            logger.info("=" * 60)
            logger.info(f"Fields analyzed: {total_fields}")
            logger.info(f"Fields filled: {filled_count}/{total_fields} ({success_rate:.1f}%)")
            if failed_fields:
                logger.warning(f"Failed fields: {', '.join(failed_fields)}")
            logger.info(f"Duration: {duration:.2f} seconds")
            logger.info(f"Status: {'SUCCESS' if filled_count == total_fields else 'PARTIAL'}")
            logger.info("=" * 60)
            
            # Return success if at least 50% of fields were filled
            return 0 if filled_count > 0 else 1
            
        except Exception as e:
            logger.error(f"AI Agent Critical Error: {e}", exc_info=True)
            return 1
        finally:
            browser.close()
            logger.info("Browser closed")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="AI Form Filling Agent - Intelligently fills web forms using AI",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python main.py                                    # AI agent with defaults
  python main.py --resume myresume.pdf              # Custom resume
  python main.py --url https://form.example.com     # Any form URL (AI adapts!)
  python main.py --visible --screenshot             # See AI in action
        """
    )
    
    parser.add_argument('--resume', default='resume.pdf',
                        help='Path to resume PDF file (default: resume.pdf)')
    parser.add_argument('--profile', default='profile.json',
                        help='Path to profile JSON file (default: profile.json)')
    parser.add_argument('--url',
                        help=f'Target form URL (default: {DEFAULT_URL})')
    parser.add_argument('--visible', action='store_true',
                        help='Show browser window to watch AI agent work')
    parser.add_argument('--screenshot', action='store_true',
                        help='Take screenshot after AI fills form')
    
    args = parser.parse_args()
    
    exit_code = main(
        resume_path=args.resume,
        profile_path=args.profile,
        url=args.url,
        headless=not args.visible,
        screenshot=args.screenshot
    )
    
    exit(exit_code)
